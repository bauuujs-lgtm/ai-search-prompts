function promptFor(category, topic) {
  const common = "请联网搜索并整理";
  const end = "要求标注信息来源和日期，优先使用官方资料、权威媒体、真实用户反馈或可验证页面。请用表格输出关键发现，再给出结论、风险提醒和下一步行动建议。不要编造来源，不要给违规操作方法。";
  if (category === "赚钱副业") return `${common} ${topic}。按启动成本、需要技能、变现周期、获客渠道、风险等级、适合人群做表格对比，并筛选 3 个最适合普通人第一周验证的方向。${end}`;
  if (category === "内容运营") return `${common} ${topic}。提炼高频标题结构、用户痛点、评论区需求、内容角度、标签和可复用脚本，并给出 20 个可发布选题。${end}`;
  if (category === "商业调研") return `${common} ${topic}。按目标用户、价格、核心卖点、获客渠道、用户好评、用户差评、可借鉴点和差异化机会做分析。${end}`;
  if (category === "电商选品") return `${common} ${topic}。按需求证据、竞争强度、价格区间、利润空间、供应链难度、售后风险、内容种草角度做表格，并排除侵权、灰产和高合规风险产品。${end}`;
  if (category === "AI工具") return `${common} ${topic}。至少列出 8 个候选工具，按官网、主要功能、免费额度、付费价格、中文支持、适合人群、优点和缺点做表格，并推荐 3 个新手可用方案。${end}`;
  if (category === "购物决策") return `${common} ${topic}。整理价格区间、主要渠道、评测观点、用户差评、替代选择、购买时机和避坑建议，最后给出买/不买/等待降价的判断。${end}`;
  if (category === "学习研究") return `${common} ${topic}。整理资料来源、核心观点、学习顺序、适合人群、难度、练习项目和 30 天学习计划。${end}`;
  if (category === "求职职业") return `${common} ${topic}。整理岗位职责、技能要求、薪资区间、作品集要求、面试题、简历关键词和 30 天准备计划。${end}`;
  if (category === "合规风险") return `${common} ${topic}。按风险等级列出规则来源、可能问题、后果、合规替代做法和需要人工确认的事项。不要提供规避监管或绕过平台风控的方法。`;
  return `${common} ${topic}。整理关键资料、价格或成本、适合人群、注意事项、风险点和可执行清单。涉及医疗、法律、保险等专业事项时，请明确提醒咨询专业人士。${end}`;
}

